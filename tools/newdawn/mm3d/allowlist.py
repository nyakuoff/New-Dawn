#!/usr/bin/env python3
"""Generate the runtime MM3D allowlist directly from the Stage A markdown report."""
import argparse
import hashlib
from pathlib import Path
import re
import sys
import json

sys.path.insert(0, str(Path(__file__).resolve().parent))
import n64anim  # noqa: E402


def generate(report, output, o2r, anim_report):
    animated = n64anim.animated_scenes(o2r)
    if anim_report.exists():  # scenes whose every animated material maps onto MM3D (animmap.py) stay in
        mapped = {k.upper() for k, v in json.loads(anim_report.read_text()).items() if v['ok']}
        animated -= mapped
    text = report.read_text()
    allowed = []
    seen = set()
    verdicts = {'candidate; inspect seams/walls', 'needs local visual adaptation'}
    for line in text.splitlines():
        columns = [s.strip() for s in line.split('|')[1:-1]]
        if not columns or not re.fullmatch(r'0x[0-9A-Fa-f]+', columns[0]):
            continue
        if len(columns) != 11 or not re.fullmatch(r'[a-z0-9_]+', columns[1]):
            raise ValueError('unexpected collision report table layout')
        sid, name, verdict = int(columns[0], 16), columns[1], columns[-1]
        if sid in seen:
            raise ValueError('duplicate scene ID in report')
        seen.add(sid)
        if verdict in verdicts:
            if name.upper() not in animated:  # animated scenes return once animation is supported
                allowed.append((sid, name))
        elif verdict not in {'unsafe wholesale overlay', 'no sampled floors'}:
            raise ValueError(f'unknown verdict: {verdict}')
    if not allowed or not seen:
        raise ValueError('empty collision report/allowlist')
    lines = ['// Generated by tools/newdawn/mm3d/allowlist.py; do not hand-edit.',
             '// Source: collision-report.md SHA-256 '+hashlib.sha256(report.read_bytes()).hexdigest(),
             '// Excludes candidate scenes with N64 texture animation (TexAnim) unless animmap.py mapped it fully']
    lines.extend(f'MM3D_SCENE(0x{sid:02X}, "{name}")' for sid, name in sorted(allowed))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines)+'\n')
    print(f'{len(allowed)} allowlisted scenes from {len(seen)} report rows -> {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report', type=Path, default=Path.home() / 'dev/ghm-mods/mm3d/out/collision-report.md')
    parser.add_argument('--out', type=Path, default=Path(__file__).resolve().parents[3]/'mm/2s2h/Enhancements/Graphics/MM3DAllowlist.inc')
    parser.add_argument('--o2r', type=Path, default=n64anim.DEFAULT_O2R)
    parser.add_argument('--anim-report', type=Path, default=Path.home()/'dev/ghm-mods/mm3d/out/anim-map-report.json')
    args = parser.parse_args()
    generate(args.report, args.out, args.o2r, args.anim_report)
