#!/usr/bin/env python3
"""Regenerate libultraship/src/fast/newdawn_grass_textures.inc from material-classification.json.

Lists the scene textures classified "grass" that are opaque ground candidates (cut-outs and tiny detail textures are
foliage/ivy, not ground), by resource basename (tiny detail tiles are skipped). Run from the repository root:  python3 tools/newdawn/grass_textures.py
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
data = json.load(open(root / "tools/newdawn/material-classification.json"))


rows = []
for t in data["textures"]:
    # Alpha-carrying 4K tiles are kept: the renderer only records draws that are opaque in the game's own render state.
    if t["class"] != "grass" or t.get("excluded") not in (None, "alpha/cutout or translucent"):
        continue
    rows.append(t["resource"].rsplit("/", 1)[-1])
rows.sort()
out = root / "libultraship/src/fast/newdawn_grass_textures.inc"
with open(out, "w") as f:
    f.write("// Generated by tools/newdawn/grass_textures.py from material-classification.json. Do not edit by hand.\n")
    f.write("// Scene textures classified as grass: basename of the resource path.\n")
    for n in rows:
        f.write('"%s",\n' % n)
print(len(rows), "textures ->", out)
