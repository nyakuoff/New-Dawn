#!/usr/bin/env python3
"""Regenerate libultraship/src/fast/newdawn_grass_textures.inc from material-classification.json.

Lists the scene textures classified "grass" that are opaque ground candidates (cut-outs and tiny detail textures are
foliage/ivy, not ground), by resource basename (tiny detail tiles are skipped). Run from the repository root:  python3 tools/newdawn/grass_textures.py
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parents[2]
data = json.load(open(root / "tools/newdawn/material-classification.json"))

# Interior scenes: their green rugs, upholstery, planters and moss are not lawns. Every scene the game marks
# RESTRICTIONS_INDOORS, plus enclosed scenes with their own restriction sets.
INTERIORS = set(re.findall(r"DEFINE_SCENE\((\w+),.*RESTRICTIONS_INDOORS",
                           open(root / "mm/include/tables/scene_table.h").read()))
INTERIORS |= {"Z2_BANDROOM", "Z2_INSIDETOWER", "Z2_MUSICHOUSE", "Z2_SECOM", "Z2_DOUJOU", "Z2_KINSTA1", "Z2_TENMON_DAI",
              "Z2_KAJIYA", "Z2_POSTHOUSE", "Z2_LABO", "Z2_TAKARAKUJI", "Z2_16GORON_HOUSE", "Z2_IKNINSIDE", "Z2_TOUGITES",
              "Z2_HAKASHITA", "Z2_REDEAD", "Z2_GORON_HAKA", "Z2_KINDAN2", "Z2_OMOYA", "Z2_FISHERMAN", "Z2_TORIDE"}


def interior(resource):
    scene = resource.split("/")[2]
    return scene in INTERIORS


rows, sway = [], []
for t in data["textures"]:
    # Plant cut-outs (leaf and grass cards) are the only room geometry that sways; outdoor scenes only.
    if t["class"] == "grass" and t.get("excluded") == "alpha/cutout or translucent" and not interior(t["resource"]):
        sway.append(t["resource"].rsplit("/", 1)[-1])

    # Alpha-carrying 4K tiles are kept: the renderer only records draws that are opaque in the game's own render state.
    if t["class"] != "grass" or t.get("excluded") not in (None, "alpha/cutout or translucent"):
        continue
    if interior(t["resource"]):
        continue
    rows.append(t["resource"].rsplit("/", 1)[-1])
rows.sort()
out = root / "libultraship/src/fast/newdawn_grass_textures.inc"
with open(out, "w") as f:
    f.write("// Generated by tools/newdawn/grass_textures.py from material-classification.json. Do not edit by hand.\n")
    f.write("// Scene textures classified as grass: basename of the resource path.\n")
    for n in rows:
        f.write('"%s",\n' % n)
sway = sorted(set(sway))
out2 = root / "libultraship/src/fast/newdawn_sway_textures.inc"
with open(out2, "w") as f:
    f.write("// Generated by tools/newdawn/grass_textures.py. Do not edit by hand.\n")
    f.write("// Outdoor cut-out textures classified as plants: the only room geometry the wind sways.\n")
    for n in sway:
        f.write('"%s",\n' % n)
print(len(sway), "sway textures ->", out2)
print(len(rows), "textures ->", out)
