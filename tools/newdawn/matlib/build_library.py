#!/usr/bin/env python3
"""Build the shipped base material library (ND-016): download the CC0 sets listed in library.json from ambientCG, re-encode to
1024x1024 JPEG (albedo, normal GL, roughness, height), and write manifest.json + MANIFEST.md for mm/assets/newdawn/materials/.
Downloads are untrusted data: they go to their own folder (--dl), only whitelisted map files are read, and this script lives elsewhere.
usage (run with -I): build_library.py --dl DIR --out mm/assets/newdawn/materials [--size 1024]"""
import argparse, hashlib, io, json, os, sys, urllib.request, zipfile, datetime
from PIL import Image, ImageFile
ImageFile.MAXBLOCK = 1 << 26

UA = {'User-Agent': 'newdawn-asset-build/0.1'}
MAPS = {'albedo': ('Color', 'RGB', 90), 'normal': ('NormalGL', 'RGB', 92), 'rough': ('Roughness', 'L', 90), 'height': ('Displacement', 'L', 90)}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=180) as r: return r.read()


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--dl', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--size', type=int, default=1024); ap.add_argument('--list', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'library.json'))
    a = ap.parse_args(); os.makedirs(a.dl, exist_ok=True); os.makedirs(a.out, exist_ok=True)
    mats = [m for m in json.load(open(a.list))['materials']]
    lic = get('https://docs.ambientcg.com/license/').decode('utf8', 'replace')
    assert 'CC0 1.0 Universal' in lic, 'ambientCG licence page no longer states CC0 1.0'
    out = []; total = 0
    for m in mats:
        aid = m['asset']; zp = f'{a.dl}/{aid}_2K-JPG.zip'
        if not os.path.exists(zp): open(zp, 'wb').write(get(f'https://ambientcg.com/get?file={aid}_2K-JPG.zip'))
        raw = open(zp, 'rb').read(); info = json.loads(get(f'https://ambientcg.com/api/v2/full_json?id={aid}'))['foundAssets'][0]
        files = {}
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            names = {os.path.basename(n): n for n in z.namelist() if '/' not in n}
            for key, (suf, mode, q) in MAPS.items():
                n = next((v for k, v in names.items() if k.endswith(f'_{suf}.jpg') or k.endswith(f'_{suf}.png')), None)
                if n is None: print('  missing', aid, key); continue
                im = Image.open(io.BytesIO(z.read(n))).convert(mode).resize((a.size, a.size), Image.LANCZOS)
                fn = f'{m["id"]}.{key}.jpg'; im.save(f'{a.out}/{fn}', 'JPEG', quality=q, subsampling=0 if mode == 'RGB' else 0, optimize=True)
                files[key] = fn; total += os.path.getsize(f'{a.out}/{fn}')
        out.append(dict(m, source=dict(name='ambientCG', asset=aid, page=f'https://ambientcg.com/view?id={aid}', download=f'https://ambientcg.com/get?file={aid}_2K-JPG.zip',
                                       license='CC0-1.0', license_page='https://docs.ambientcg.com/license/', zip_sha256=hashlib.sha256(raw).hexdigest(), fetched=str(datetime.date.today())),
                        files=files, size=a.size, size_cm=[info.get('dimensionX'), info.get('dimensionY')], display=info.get('displayName') or aid))
        print(f'{m["id"]:20s} {sum(os.path.getsize(a.out + "/" + f) for f in files.values()) / 1e6:5.2f} MB', flush=True)
    json.dump(dict(version=1, size=a.size, note='generated by tools/newdawn/matlib/build_library.py; do not edit', materials=out), open(f'{a.out}/manifest.json', 'w'), indent=1)
    L = ['# New Dawn base material library (ND-016)', '', 'CC0 PBR materials from ambientCG (https://ambientcg.com, licence https://docs.ambientcg.com/license/, "CC0 1.0 Universal"), re-encoded by',
         '`tools/newdawn/matlib/build_library.py` to 1024x1024 JPEG (albedo, normal GL, roughness, height; AO and the 2K originals are not shipped).',
         'Used only as input to the first-run texture generator (`mm/2s2h/NewDawn/RuntimeTextures.cpp`): the player never sees them unmodified.',
         f'Total: {total / 1e6:.1f} MB for {len(out)} sets. Add or swap a set by editing `library.json` and rerunning the tool.', '',
         '| id | class | roles | region | asset | page | zip sha256 |', '|---|---|---|---|---|---|---|']
    for m in out:
        s = m['source']; L.append(f"| {m['id']} | {m['class']} | {', '.join(m['roles'])} | {m['region']} | {s['asset']} | {s['page']} | `{s['zip_sha256'][:16]}...` |")
    L += ['', 'Licence evidence: the ambientCG licence page (fetched by the tool; the build aborts if it stops saying "CC0 1.0 Universal"). ambientCG\'s API has no per-asset licence field.']
    open(f'{a.out}/MANIFEST.md', 'w').write('\n'.join(L) + '\n'); print(f'total {total / 1e6:.1f} MB, {len(out)} sets')


if __name__ == '__main__':
    main()
